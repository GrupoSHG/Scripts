-- ============================================================================
-- Schema cys: CRM de CyS (GoHighLevel) y sus proyectos, igual al schema m5.
--
-- Lo llena CyS_Systems/sync_ghl_cys.py llamando a cys.sincronizar_ghl(etapas, oportunidades):
--   - cys.pipeline_etapas  etapas del pipeline "Negocios" con su probabilidad (editable;
--                          la sincronización no la pisa una vez cargada),
--   - cys.oportunidades    copia completa de las oportunidades (se reemplaza en cada corrida),
--   - cys.proyectos        un proyecto por cada oportunidad ganada (estado won o etapa al 100 %),
--                          con carta Gantt (proyecto_etapas), flujo (proyecto_flujo) y
--                          presupuesto por partida (proyecto_partidas) que se cargan en la página.
--
-- Copiado de la definición viva de m5 (28/10/2026), sin lo que es solo de M5: portal de
-- clientes (proyecto_clientes), licitaciones y precios. Mismas políticas: lee y edita
-- cualquier usuario con sesión, salvo los roles 'cliente' y 'vendedor' (restrictivas).
--
-- Se aplica a mano: supabase --workdir <tmp> db query --linked -f CyS_Systems/crm_cys.sql
-- Idempotente salvo el alter role del final, que repite la lista viva de schemas expuestos
-- (revisarla antes: select rolconfig from pg_roles where rolname = 'authenticator').
-- ============================================================================
create schema if not exists cys;
grant usage on schema cys to authenticated, service_role;

create table if not exists cys.pipeline_etapas (
  etapa_id        text primary key,
  pipeline_id     text not null,
  pipeline_nombre text,
  etapa_nombre    text not null,
  orden           integer,
  probabilidad    integer,
  actualizado_en  timestamptz default now()
);

create table if not exists cys.oportunidades (
  id              text primary key,
  nombre          text,
  pipeline_id     text,
  pipeline_nombre text,
  etapa_id        text,
  etapa_nombre    text,
  etapa_orden     integer,
  estado          text,
  monto           numeric,
  contacto        text,
  empresa         text,
  asignado_a      text,
  fuente          text,
  creada_en       timestamptz,
  cambio_etapa_en timestamptz,
  actualizada_en  timestamptz,
  sincronizado_en timestamptz default now(),
  campos          jsonb not null default '{}'::jsonb
);

create table if not exists cys.proyectos (
  id                    uuid primary key default gen_random_uuid(),
  oportunidad_id        text unique,
  nombre                text not null,
  cliente               text,
  ot                    text,
  cotizacion            text,
  oc_cliente            text,
  oc_recibida_en        date,
  forma_pago            text,
  link_contrato         text,
  presupuesto_comercial numeric,
  presupuesto_obra      numeric,
  fecha_inicio          date,
  fecha_fin             date,
  estado                text default 'activo',
  notas                 text,
  actualizado_en        timestamptz default now()
);

create table if not exists cys.proyecto_etapas (
  id          bigint generated by default as identity primary key,
  proyecto_id uuid not null references cys.proyectos(id) on delete cascade,
  orden       integer not null,
  nombre      text not null,
  descripcion text,
  responsable text,
  inicio      date,
  fin         date,
  avance_pct  integer default 0
);

create table if not exists cys.proyecto_flujo (
  id          bigint generated by default as identity primary key,
  proyecto_id uuid not null references cys.proyectos(id) on delete cascade,
  fecha       date not null,
  concepto    text not null,
  tipo        text not null check (tipo in ('ingreso', 'egreso')),
  monto       numeric not null,
  real        boolean default false
);

create table if not exists cys.proyecto_partidas (
  id             bigint generated by default as identity primary key,
  proyecto_id    uuid not null references cys.proyectos(id) on delete cascade,
  grupo          text,
  descripcion    text not null,
  cantidad       numeric,
  valor_unitario numeric,
  valor_total    numeric,
  proveedor      text
);

-- Permisos y RLS como en m5.
grant all on cys.pipeline_etapas, cys.oportunidades, cys.proyectos,
             cys.proyecto_etapas, cys.proyecto_flujo, cys.proyecto_partidas to authenticated, service_role;
grant usage on all sequences in schema cys to authenticated, service_role;

do $$
declare t text;
begin
  foreach t in array array['pipeline_etapas', 'oportunidades', 'proyectos',
                           'proyecto_etapas', 'proyecto_flujo', 'proyecto_partidas'] loop
    execute format('alter table cys.%I enable row level security', t);
    execute format('drop policy if exists lectura_autenticados on cys.%I', t);
    execute format('create policy lectura_autenticados on cys.%I for select to authenticated using (true)', t);
    execute format('drop policy if exists sin_clientes_externos on cys.%I', t);
    execute format($p$create policy sin_clientes_externos on cys.%I as restrictive for all to authenticated
                      using ((select coalesce(shg_dashboards.rol_actual(), '')) <> 'cliente')$p$, t);
    execute format('drop policy if exists vendedor_solo_lo_suyo on cys.%I', t);
    execute format($p$create policy vendedor_solo_lo_suyo on cys.%I as restrictive for all to authenticated
                      using (not (select shg_dashboards.es_vendedor()))
                      with check (not (select shg_dashboards.es_vendedor()))$p$, t);
  end loop;
end $$;

-- En la página se editan la ficha del proyecto y el avance de la carta Gantt.
drop policy if exists edicion_autenticados on cys.proyectos;
create policy edicion_autenticados on cys.proyectos for update to authenticated using (true) with check (true);
drop policy if exists edicion_autenticados on cys.proyecto_etapas;
create policy edicion_autenticados on cys.proyecto_etapas for update to authenticated using (true) with check (true);

-- Sincronización desde GHL (solo service_role).
create or replace function cys.sincronizar_ghl(etapas jsonb, oportunidades jsonb)
returns jsonb language plpgsql set search_path = cys as $$
declare n_etapas int; n_opps int; n_proy int;
begin
  -- Etapas: se actualizan nombre y orden; la probabilidad se conserva si ya existía (es editable).
  insert into cys.pipeline_etapas (etapa_id, pipeline_id, pipeline_nombre, etapa_nombre, orden, probabilidad, actualizado_en)
  select e.etapa_id, e.pipeline_id, e.pipeline_nombre, e.etapa_nombre, e.orden, e.probabilidad, now()
  from jsonb_populate_recordset(null::cys.pipeline_etapas, etapas) e
  on conflict (etapa_id) do update set
    pipeline_id = excluded.pipeline_id, pipeline_nombre = excluded.pipeline_nombre,
    etapa_nombre = excluded.etapa_nombre, orden = excluded.orden, actualizado_en = now();
  get diagnostics n_etapas = row_count;

  if jsonb_array_length(oportunidades) = 0 then
    raise exception 'GHL no devolvió oportunidades: no se reemplaza cys.oportunidades';
  end if;
  delete from cys.oportunidades where true;
  insert into cys.oportunidades select * from jsonb_populate_recordset(null::cys.oportunidades, oportunidades);
  get diagnostics n_opps = row_count;
  update cys.oportunidades set sincronizado_en = now(), campos = coalesce(campos, '{}'::jsonb) where true;

  -- Cada oportunidad ganada es un proyecto; los campos de obra quedan por cargar en la página.
  -- El monto del CRM incluye IVA, el presupuesto comercial es neto.
  insert into cys.proyectos (oportunidad_id, nombre, cliente, presupuesto_comercial, estado)
  select o.id, coalesce(nullif(o.nombre, ''), 'Proyecto sin nombre'), coalesce(o.empresa, o.contacto),
         round(o.monto / 1.19), 'activo'
  from cys.oportunidades o
  left join cys.pipeline_etapas e on e.etapa_id = o.etapa_id
  where o.estado = 'won' or (o.estado = 'open' and e.probabilidad = 100)
  on conflict (oportunidad_id) do nothing;
  get diagnostics n_proy = row_count;

  return jsonb_build_object('etapas', n_etapas, 'oportunidades', n_opps, 'proyectos_nuevos', n_proy);
end $$;
revoke all on function cys.sincronizar_ghl(jsonb, jsonb) from public, anon, authenticated;
grant execute on function cys.sincronizar_ghl(jsonb, jsonb) to service_role;

